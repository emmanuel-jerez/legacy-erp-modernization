"""Write an approved migration to ``<out_dir>/<function>/``.

Files: the accepted module (byte-identical to the one that passed parity), golden cases,
the data snapshot, the model's spec, a generated pytest characterization test, a dated
parity report (JSON and Markdown), the approval record, and the run's audit log.
"""

from __future__ import annotations

import hashlib
import json
import re
import shutil
from pathlib import Path
from typing import Any

from erp_sandbox.llm import ModelResult, UsageTally

from . import config
from .extract import LegacySource


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def decision_label(decision: dict[str, Any]) -> str:
    if decision.get("auto"):
        return "AUTO-APPROVED (flag, not a human review)"
    return "APPROVED" if decision.get("approved") else "REJECTED"


def usage_summary(calls: list[dict[str, Any]]) -> dict[str, Any]:
    """``UsageTally`` totals (plus token sums) from the call records kept in graph state."""
    tally = UsageTally()
    tokens: dict[str, int] = {}
    for c in calls:
        tally.add(ModelResult(data={}, model=c["model"], effort=c["effort"], key="", from_cassette=c["from_cassette"],
                              duration_ms=c.get("duration_ms"), cost_usd_estimate=c.get("cost_usd_estimate"),
                              usage=c.get("usage") or {}))
        for k, v in (c.get("usage") or {}).items():
            if isinstance(v, int):
                tokens[k] = tokens.get(k, 0) + v
    return {**tally.as_dict(), "tokens_as_recorded": dict(sorted(tokens.items()))}


def parity_summary(state: dict[str, Any]) -> dict[str, Any]:
    cases = state.get("cases", [])
    vis, held = state.get("visible_report", {}), state.get("held_out_report", {})
    return {
        "function": state["function"],
        "status": state.get("status"),
        "cases": {
            "total": len(cases),
            "sampled": sum(c["source"] == "sampled" for c in cases),
            "edge": sum(c["source"] == "edge" for c in cases),
            "visible": sum(c["split"] == "visible" for c in cases),
            "held_out": sum(c["split"] == "held_out" for c in cases),
            "rejected": len(state.get("rejected", [])),
        },
        "visible": {k: vis.get(k) for k in ("matched", "total", "rate", "passed", "runner_failure")},
        "held_out": {k: held.get(k) for k in ("matched", "total", "rate", "passed", "runner_failure")},
        "repair_iterations": state.get("iteration", 0),
        "history": state.get("history", []),
    }


def _report_markdown(summary: dict[str, Any], decision: dict[str, Any], usage: dict[str, Any], state: dict[str, Any]) -> str:
    c, v, h = summary["cases"], summary["visible"], summary["held_out"]
    lines = [
        f"# Parity report: adempiere.{summary['function']}",
        "",
        f"- Decided: {decision['decided_at']}, {decision_label(decision)} by {decision['approver']}",
        f"- Run: `{state['run_id']}`",
        f"- Oracle: the legacy PL/pgSQL function in database `{config.DB_NAME}`, TimeZone {config.SESSION_TIMEZONE}",
        f"- Cases: {c['total']} ({c['sampled']} sampled from seed data, {c['edge']} model-proposed edge cases; "
        f"{c['rejected']} candidate cases rejected)",
        f"- Visible parity: {v['matched']}/{v['total']}",
        f"- **Held-out parity: {h['matched']}/{h['total']}** (pass bar: 100%)",
        f"- Repair iterations: {summary['repair_iterations']}",
        f"- Model calls: {usage['calls']} ({usage['live_calls']} live, {usage['cassette_hits']} from cassettes); "
        f"models {', '.join(usage['models'])}; effort {', '.join(usage['efforts'])}; recorded cost estimate "
        f"${usage['cost_usd_estimate_as_recorded']:.2f} (Claude Code client-side estimate)",
        "",
        "## Iterations",
        "",
        "| Iteration | Visible matched |",
        "|---|---|",
    ]
    for item in summary["history"]:
        note = f" (runner: {item['runner_failure'][:80]})" if item.get("runner_failure") else ""
        lines.append(f"| {item['iteration']} | {item['visible_matched']}/{item['visible_total']}{note} |")
    lines += ["", "## What this proves and does not", "",
              "Parity holds on the recorded cases, including held-out cases whose golden outputs no prompt ever",
              "contained. It is evidence of equivalence, not a proof: see docs/metric-contract.md.", ""]
    return "\n".join(lines)


TEST_TEMPLATE = '''"""Characterization tests for the migrated adempiere.{function}.

Generated by erp-migration-agent on approval; regenerate rather than edit. The golden outputs
were recorded from the legacy PL/pgSQL function (the oracle).
"""

from __future__ import annotations

from pathlib import Path

import pytest

from erp_migration_agent.oracle import Oracle, is_available
from erp_migration_agent.pinned import check_legacy, check_port, load_json, load_module

HERE = Path(__file__).parent
GOLDEN = load_json(HERE / "golden_cases.json")
SNAPSHOT = load_json(HERE / "snapshot.json")
CASES = GOLDEN["cases"]
IDS = [c["id"] for c in CASES]


@pytest.fixture(scope="module")
def port():
    return load_module(HERE / "{function}.py")


@pytest.fixture(scope="module")
def legacy():
    if not is_available():
        pytest.skip("legacy database is not running")
    with Oracle.open() as oracle:
        yield oracle, oracle.extract("{function}")


@pytest.mark.parametrize("case", CASES, ids=IDS)
def test_port_reproduces_golden_output(port, case):
    check_port(port, GOLDEN, SNAPSHOT, case)


@pytest.mark.integration
@pytest.mark.parametrize("case", CASES, ids=IDS)
def test_legacy_still_produces_golden_output(legacy, case):
    oracle, source = legacy
    check_legacy(oracle, source, case)
'''


_REPORT = re.compile(r"^parity-report-\d{4}-\d{2}-\d{2}\.(md|json)$")


class PublishRefused(RuntimeError):
    """The output folder holds files this tool did not generate; it is never replaced."""


def _check_replaceable(target: Path, generated: set[str]) -> None:
    """Only a previous publication (with ``approval.json`` and generated files only) is replaced."""
    if not target.exists():
        return
    names = {p.name for p in target.iterdir()}
    foreign = sorted(n for n in names if n not in generated and not _REPORT.match(n) and n != "__pycache__")
    if "approval.json" not in names or foreign:
        detail = f"unexpected files: {', '.join(foreign)}" if foreign else "no approval.json"
        raise PublishRefused(f"refusing to replace {target}: it is not a previous publication ({detail})")


def publish(state: dict[str, Any], out_dir: Path, run_dir: Path) -> list[str]:
    fn = state["function"]
    decision = state["decision"]
    target = out_dir / fn
    source = LegacySource.from_dict(state["source"])
    snapshot = json.loads(Path(state["snapshot_path"]).read_text(encoding="utf-8"))
    day = decision["decided_at"][:10]
    summary = parity_summary(state)
    usage = usage_summary(state.get("calls", []))
    golden = {
        "function": fn,
        "arg_names": source.function.arg_names,
        "arg_types": source.function.arg_types,
        "return_type": source.function.return_type,
        "session_tz": snapshot["session_tz"],
        "cases": sorted(state["cases"], key=lambda c: (c["split"], c["id"])),
    }
    files: dict[str, str] = {
        f"{fn}.py": state["module_source"],
        "golden_cases.json": json.dumps(golden, indent=1, ensure_ascii=False) + "\n",
        "snapshot.json": json.dumps(snapshot, indent=1) + "\n",
        "spec.json": json.dumps(state["spec"], indent=2, ensure_ascii=False) + "\n",
        f"test_{fn}_characterization.py": TEST_TEMPLATE.format(function=fn),
        f"parity-report-{day}.json": json.dumps({**summary, "decision": decision, "usage": usage,
                                                 "visible_report": state["visible_report"],
                                                 "held_out_report": state["held_out_report"]},
                                                indent=2, ensure_ascii=False) + "\n",
        f"parity-report-{day}.md": _report_markdown(summary, decision, usage, state),
    }
    files["approval.json"] = json.dumps({
        "function": fn,
        "run_id": state["run_id"],
        **decision,
        "parity": {"visible": summary["visible"], "held_out": summary["held_out"],
                   "repair_iterations": summary["repair_iterations"], "cases": summary["cases"]},
        "module_sha256": _sha256(state["module_source"]),
        "golden_cases_sha256": _sha256(files["golden_cases.json"]),
    }, indent=2) + "\n"
    _check_replaceable(target, set(files) | {"audit.jsonl"})
    # Build the whole directory beside the target, then swap it in through a backup, so a
    # failure at any point leaves either the previous or the new publication in place, never a
    # partial one, and the publish step can simply be retried.
    staging = out_dir / f".{fn}.staging"
    backup = out_dir / f".{fn}.previous"
    for leftover in (staging, backup):
        if leftover.exists():
            shutil.rmtree(leftover)
    try:
        staging.mkdir(parents=True)
        for name, text in files.items():
            (staging / name).write_text(text, encoding="utf-8")
        audit = run_dir / "audit.jsonl"
        if audit.exists():
            shutil.copyfile(audit, staging / "audit.jsonl")
        if target.exists():
            target.rename(backup)
        staging.rename(target)
    except OSError:
        if backup.exists() and not target.exists():
            backup.rename(target)
        raise
    finally:
        for leftover in (staging, backup):
            if leftover.exists():
                shutil.rmtree(leftover)
    return sorted(str(p) for p in target.iterdir())
